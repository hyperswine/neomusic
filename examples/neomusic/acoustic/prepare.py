#!/usr/bin/env python3
"""Prepare pinned, external piano/guitar assets and NeoMusic's baseline SFZ maps.

Run with --fetch to download missing archives; otherwise preparation is offline.
Requires Python 3 and FFmpeg. Recordings stay under --samples, outside Git.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tarfile
import urllib.request
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
STRINGS = [(40, 'LowE'), (45, 'A'), (50, 'D'), (55, 'G'), (59, 'B'), (64, 'HighE')]
PIANO_VELOCITIES = [(1,26),(27,34),(35,36),(37,43),(44,46),(47,50),(51,56),(57,64),
                    (65,72),(73,80),(81,88),(89,96),(97,104),(105,112),(113,120),(121,127)]


def sha256(path):
    digest = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1024*1024), b''):
            digest.update(block)
    return digest.hexdigest()


def note_name(key, sharp='#'):
    names = ['C','C'+sharp,'D','D'+sharp,'E','F','F'+sharp,'G','G'+sharp,'A','A'+sharp,'B']
    return names[key % 12] + str(key // 12 - 1)


def piano_regions():
    regions = []
    for layer, (vlo, vhi) in enumerate(PIANO_VELOCITIES, 1):
        for key in range(21, 109, 3):
            regions.append(dict(sample=f'{note_name(key)}v{layer}.wav', pitch_keycenter=key,
                                lokey=max(21,key-1), hikey=min(108,key+1), lovel=vlo, hivel=vhi))
    return regions


def guitar_regions(kind, style='auto'):
    nylon = kind == 'nylon'
    if not nylon and style != 'auto':
        raise ValueError('steel guitar has only the auto mapping')
    layers = ([(1,1,42),(2,43,85),(3,86,127)] if nylon else [(1,1,48),(2,49,96),(3,97,127)])
    if style == 'finger': layers = [(1,1,127)]
    elif style == 'pick': layers = [(2,1,64),(3,65,127)]
    elif style != 'auto': raise ValueError('unknown nylon style')
    regions = []
    for key in range(40, 84 if nylon else 85):
        string = next(name for low, name in reversed(STRINGS) if low <= key)
        for layer, vlo, vhi in layers:
            technique = ('Finger' if layer == 1 else 'Pick') if nylon else ''
            filename = f'INSGuitar{kind.title()}_String{string}_Vel{layer:02}{technique}_{note_name(key,"s")}_01.wav'
            regions.append(dict(sample=filename, key=key, lovel=vlo, hivel=vhi))
    return regions


def mappings():
    return {'salamander': ('salamander', piano_regions()),
            'meta-nylon': ('meta-nylon-guitar', guitar_regions('nylon')),
            'meta-nylon-finger': ('meta-nylon-guitar', guitar_regions('nylon','finger')),
            'meta-nylon-pick': ('meta-nylon-guitar', guitar_regions('nylon','pick')),
            'meta-steel': ('meta-steel-guitar', guitar_regions('steel'))}


def write_maps(output):
    output.mkdir(parents=True, exist_ok=True)
    for name, (folder, regions) in mappings().items():
        lines = ['// Generated by prepare.py; see README.md for sources, credits and limitations.',
                 '// Baseline mapping: natural attacks, no loops; note release is controlled by the voice.',
                 f'<control> default_path=neo-acoustic/{folder}/']
        lines += ['<region> loop_mode=no_loop ' + ' '.join(f'{k}={v}' for k,v in r.items()) for r in regions]
        (output/(name+'.sfz')).write_text('\n'.join(lines)+'\n')


def archive_for(source, directory, fetch):
    path = directory / source['archive']
    if not path.exists():
        if not fetch:
            raise ValueError(f'missing {path}; pass --fetch to download the pinned archive')
        directory.mkdir(parents=True, exist_ok=True)
        part = path.with_name(path.name+'.part')
        print(f"Downloading {source['id']} ({source['url']})", flush=True)
        with urllib.request.urlopen(source['url'],timeout=120) as response, part.open('wb') as dst:
            shutil.copyfileobj(response, dst, 1024*1024)
        if sha256(part) != source['sha256']:
            raise ValueError(f'checksum mismatch: {part}')
        part.replace(path)
    if sha256(path) != source['sha256']:
        raise ValueError(f'checksum mismatch: {path}')
    return path


def save_stream(stream, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    part = target.with_name(target.name+'.part')
    with part.open('wb') as out:
        shutil.copyfileobj(stream, out, 1024*1024)
    part.replace(target)


def prepare(source, archive, assets):
    dest = assets/source['id']
    dest.mkdir(parents=True,exist_ok=True)
    provenance = dest/'upstream'
    provenance.mkdir(exist_ok=True)
    if source['id'] == 'salamander':
        expected = {r['sample'].replace('.wav','.flac') for r in piano_regions()}
        found = set()
        ffmpeg = shutil.which('ffmpeg')
        if not ffmpeg: raise ValueError('FFmpeg is required to decode Salamander FLAC recordings')
        with tarfile.open(archive, 'r:gz') as bundle:
            for member in bundle:
                if not member.isfile(): continue
                path = Path(member.name)
                stream = bundle.extractfile(member)
                if path.parent.name == 'Samples' and path.name in expected:
                    if path.name in found: raise ValueError('duplicate sample: '+path.name)
                    found.add(path.name)
                    flac = dest/path.name
                    save_stream(stream,flac)
                    wav = flac.with_suffix('.wav')
                    part = wav.with_name(wav.name+'.part')
                    subprocess.run([ffmpeg,'-nostdin','-v','error','-y','-i',str(flac),
                                    '-c:a','pcm_s24le','-f','wav',str(part)],check=True)
                    part.replace(wav)
                    flac.unlink()
                elif len(path.parts)==2 and path.name in ('LICENSE','README.md','Salamander Grand Piano V3.sfz'):
                    save_stream(stream,provenance/path.name)
                elif path.parent.name=='Data' and path.suffix=='.txt':
                    save_stream(stream,provenance/'Data'/path.name)
        if found != expected: raise ValueError(f'Salamander missing {sorted(expected-found)}')
    else:
        found = set()
        with zipfile.ZipFile(archive) as bundle:
            for info in bundle.infolist():
                path = Path(info.filename)
                if info.is_dir() or '__MACOSX' in path.parts: continue
                if re.fullmatch(r'INSGuitar(?:Nylon|Steel)_[A-Za-z0-9_]+\.wav',path.name):
                    if path.name in found: raise ValueError('duplicate sample: '+path.name)
                    found.add(path.name)
                    with bundle.open(info) as stream: save_stream(stream,dest/path.name)
                elif path.name in ('LICENSE','README.md','SHA256SUMS','manifest.json') or path.suffix=='.sfz':
                    with bundle.open(info) as stream: save_stream(stream,provenance/path.name)
        if len(found) != source['sample_count']:
            raise ValueError(f"{source['id']}: expected {source['sample_count']} samples, found {len(found)}")
    required = {r['sample'] for folder,regions in mappings().values() if folder==source['id'] for r in regions}
    missing = [name for name in required if not (dest/name).is_file()]
    if missing: raise ValueError(f'missing mapped samples: {missing}')
    if not (provenance/'LICENSE').is_file(): raise ValueError(f'missing upstream license in {archive}')
    # Fingerprints cover every prepared file, including converted piano recordings.
    manifest = dict(source=source, files=[dict(file=p.name,bytes=p.stat().st_size,sha256=sha256(p))
                                       for p in sorted(dest.glob('*.wav'))])
    (dest/'prepared.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f"Prepared {source['id']}: {len(manifest['files'])} WAV files",flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--samples',type=Path,required=True,help='external NEOMUSIC_SAMPLES directory')
    parser.add_argument('--archive-dir',type=Path,help='verified archive cache (default: SAMPLES/neo-acoustic/downloads)')
    parser.add_argument('--output',type=Path,default=HERE,help='directory for generated SFZ maps')
    parser.add_argument('--fetch',action='store_true',help='download missing archives')
    args=parser.parse_args()
    sources=json.loads((HERE/'sources.json').read_text())
    assets=args.samples.resolve()/'neo-acoustic'
    cache=args.archive_dir or assets/'downloads'
    for source in sources:
        archive=archive_for(source,cache,args.fetch)
        prepare(source,archive,assets)
    write_maps(args.output)
    print(f'Ready: set NEOMUSIC_SAMPLES={args.samples.resolve()}',flush=True)


if __name__=='__main__':
    try: main()
    except (ValueError,OSError,subprocess.CalledProcessError) as exc:
        raise SystemExit(str(exc))
